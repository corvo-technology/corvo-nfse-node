// Generates src/types/openapi.ts (the wire types) from spec/openapi.json.
// Usage: yarn gen:types   (then the formatter runs on the output)
import { readFileSync, writeFileSync } from "node:fs";

const spec = JSON.parse(readFileSync(new URL("../spec/openapi.json", import.meta.url), "utf8"));

const refName = (ref) => ref.split("/").pop();
const key = (k) => (/^[a-zA-Z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));

function emit(schema, indent = "") {
	if (!schema || Object.keys(schema).length === 0) return "unknown";
	if (schema.$ref) return refName(schema.$ref);
	if (schema.allOf) return schema.allOf.map((s) => emit(s, indent)).join(" & ");
	let out;
	if (schema.oneOf || schema.anyOf) {
		out = (schema.oneOf ?? schema.anyOf).map((s) => emit(s, indent)).join(" | ");
	} else if (schema.enum) {
		out = schema.enum.map((v) => JSON.stringify(v)).join(" | ");
	} else if (schema.type === "array") {
		out = `Array<${emit(schema.items, indent)}>`;
	} else if (schema.type === "object" || schema.properties) {
		const required = new Set(schema.required ?? []);
		const lines = Object.entries(schema.properties ?? {}).map(([name, value]) => {
			const doc = value.description ? `${indent}\t/** ${value.description.replace(/\*\//g, "*\\/")} */\n` : "";
			return `${doc}${indent}\t${key(name)}${required.has(name) ? "" : "?"}: ${emit(value, `${indent}\t`)};`;
		});
		if (schema.additionalProperties) {
			const extra = schema.additionalProperties === true ? "unknown" : emit(schema.additionalProperties, `${indent}\t`);
			lines.push(`${indent}\t[key: string]: ${extra};`);
		}
		out = lines.length ? `{\n${lines.join("\n")}\n${indent}}` : "Record<string, unknown>";
	} else if (schema.type === "integer" || schema.type === "number") out = "number";
	else if (schema.type === "string") out = "string";
	else if (schema.type === "boolean") out = "boolean";
	else out = "unknown";
	return schema.nullable ? `${out} | null` : out;
}

const parts = [
	"// Generated by scripts/gen-types.mjs from spec/openapi.json. Do not edit by hand.\n",
];
for (const [name, schema] of Object.entries(spec.components.schemas)) {
	const isPlainObject = (schema.type === "object" || schema.properties) && !schema.allOf && !schema.nullable;
	const doc = schema.description ? `/** ${schema.description.replace(/\*\//g, "*\\/")} */\n` : "";
	if (isPlainObject && !schema.additionalProperties) {
		parts.push(`${doc}export interface ${name} ${emit(schema)}\n`);
	} else {
		parts.push(`${doc}export type ${name} = ${emit(schema)};\n`);
	}
}
writeFileSync(new URL("../src/types/openapi.ts", import.meta.url), parts.join("\n"));
console.log(`Wrote ${Object.keys(spec.components.schemas).length} schemas to src/types/openapi.ts`);
